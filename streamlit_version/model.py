def get_verdict(prob: float) -> str:
    """Определяет категорию результата и возвращает фразу."""
    if prob >= 0.95:
        category = "genius"
    elif prob >= 0.7:
        category = "good"
    elif prob >= 0.5:
        category = "maybe"
    else:
        category = "no_chance"

    phrase = random.choice(PHRASES[category])
    return phrase.format(P=prob)